"""Read existing LVGL generated UI assets; never rerasterize an 'original' baseline.

This extracts fixed sample pictures, not distributable font assets. Only the
uncompressed, sparse-tiny C format generated by the audited build_ui_fonts.py is
accepted. Unsupported formats and missing codepoints fail visibly.
"""
from __future__ import annotations
from pathlib import Path
from functools import lru_cache
import re,hashlib,zlib
from PIL import Image
from .model import FW_SIZES,TEXTS

def _array(text,name):
    m=re.search(r'\b'+re.escape(name)+r'\[\]\s*=\s*\{(.*?)\};',text,re.S)
    if not m:raise ValueError('固件原样字库格式不支持：'+name)
    return m.group(1)

def _ints(s):
    if re.sub(r'\b(?:0[xX][0-9a-fA-F]+|\d+)\b|[\s,]','',s):raise ValueError('Non-literal asset data')
    return [int(x,0) if x.lower().startswith('0x') else int(x) for x in re.findall(r'0[xX][0-9a-fA-F]+|\d+',s)]

def parse_asset(data:bytes,px:int):
    if px not in FW_SIZES or len(data)>8*1024*1024:raise ValueError('Unsupported original UI size / budget')
    text=data.decode();suffix='a'+str(px)
    bitmap=bytes(_ints(_array(text,'bitmap'+suffix)))
    unicode=_ints(_array(text,'unicode'+suffix))
    desc=[]
    for part in re.findall(r'\{([^{}]*)\}',_array(text,'glyphs'+suffix)):
        desc.append({k:int(v) for k,v in re.findall(r'\.(\w+)\s*=\s*(-?\d+)',part)})
    if len(desc)!=len(unicode)+1 or len(unicode)!=len(set(unicode)):raise ValueError('Invalid original cmap')
    dsc=re.search(r'\bdsc'+suffix+r'\s*=\s*\{(.*?)\};',text,re.S)
    if not dsc or not re.search(r'\.bpp\s*=\s*2\b',dsc[1]):raise ValueError('Expected original UI A2')
    font=re.search(r'\bui_font_'+suffix+r'\s*=\s*\{(.*?)\};',text,re.S)
    if not font:raise ValueError('Missing original font object')
    def n(k):
        m=re.search(r'\.'+k+r'\s*=\s*(-?\d+)',font[1])
        if not m:raise ValueError('Missing metric '+k)
        return int(m[1])
    line,base=n('line_height'),n('base_line')
    if not 1<=line<=100 or not 0<=base<=line:raise ValueError('Invalid original line metrics')
    return bitmap,{32+cp:desc[i+1] for i,cp in enumerate(unicode)},line,base

@lru_cache(maxsize=16)
def _load(pathstr,mtime,px):
    data=Path(pathstr).read_bytes()
    return (*parse_asset(data,px),hashlib.sha256(data).hexdigest())

def firmware_master(repo,spec,kind='compact'):
    if repo is None:raise ValueError('固件原样需读取 e-paper 仓库 main/ui_demo_fonts.c；不会用其他字体模拟')
    p=Path(repo)/'main/ui_demo_fonts.c'
    if not p.is_file():raise ValueError('缺少固件原样字库 main/ui_demo_fonts.c')
    bitmap,glyphs,line,base,sha=_load(str(p.resolve()),p.stat().st_mtime_ns,spec.px)
    w,h=(432,224) if kind=='wide' else (208,96)
    def advance(c):
        if ord(c) not in glyphs:raise ValueError('固件原样样文缺字：'+c)
        return (glyphs[ord(c)]['adv_w']+8)//16
    if spec.content=='body' and kind=='wide':
        lines=[];current='';length=0
        for c in TEXTS['body'][0]:
            a=advance(c)
            if current and length+a>w-16:lines.append(current);current='';length=0
            current+=c;length+=a
        if current:lines.append(current)
    else:lines=['清晨光线','慢慢移来'] if spec.content=='body' else list(TEXTS[spec.content])
    raw=bytearray(w*h);visible=[]
    for row,text in enumerate(lines):
        if 4+(row+1)*line>h:break
        x=8
        for c in text:
            advance(c);g=glyphs[ord(c)];gw,gh=g['box_w'],g['box_h'];idx=g['bitmap_index']
            left=x+g['ofs_x'];top=4+row*line+line-base-gh-g['ofs_y']
            if idx+(gw*gh+3)//4>len(bitmap) or left<0 or top<0 or left+gw>w or top+gh>h:raise ValueError('固件原样字形越界')
            for gy in range(gh):
                for gx in range(gw):
                    at=gy*gw+gx;v=((bitmap[idx+at//4]>>(6-2*(at%4)))&3)*85
                    pos=(top+gy)*w+left+gx;raw[pos]=max(raw[pos],v)
            x+=advance(c)
        visible.append(text)
    if not visible or (kind=='compact' and len(visible)!=len(lines)):raise ValueError('原固件行高超过样本区域')
    raw=bytes(raw);text='\n'.join(visible)
    return raw,{'width':w,'height':h,'source':{'id':'sourcehan','sha256':sha,'family':'Source Han Sans CN','style':'Medium / original ui_font_a'+str(spec.px),'weight':500,'axes':{},'identity_kind':'compiled-ui-C','filename':p.name},'visible_text':text,'text_sha256':hashlib.sha256(text.encode()).hexdigest(),'master_sha256':hashlib.sha256(raw).hexdigest(),'master_crc32':zlib.crc32(raw),'requested_px':spec.px,'resolved_px':spec.px,'kind':kind,'line_height':line,'base_line':base,'baseline_reference':'existing-ui-glyphs-and-metrics','body_continues':len(visible)<len(lines)}
